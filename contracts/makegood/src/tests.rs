fn world_with_bond(bond: u128) -> World {
    let mut w = World::new(7);
    let sid = w.sellers[0].0.clone();
    w.transfer_in(&sid, bond, json!({"action":"bond"}));
    w
}

fn pay(w: &mut World, price: u128, n: u64) -> String {
    let sid = w.sellers[0].0.clone();
    let b = w.buyers[0].clone();
    let q = format!("{:032x}", n);
    w.transfer_in(&b, price, json!({"action":"pay","seller":sid,"quote_id":q,"terms_id":"t1","request_hash":"00".repeat(32)}));
    let id = format!("{sid}/{q}");
    w.calls.push(Meta { id: id.clone(), canon: String::new(), body: String::new(), offer: 0, salt: [0; 32] });
    id
}

#[test]
fn exposure_reserve_and_free_capacity() {
    let mut w = world_with_bond(1_000_000);
    let sid = w.sellers[0].0.clone();
    pay(&mut w, 400_000, 1);
    let s = w.c.sellers.get(&sid).unwrap().clone();
    assert_eq!(s.reserved, 420_000); // price + max(0.02, 5%)
    assert_eq!(s.free(), 580_000);
    assert_eq!(w.c.treasury, 4_000);
    pay(&mut w, 400_000, 2);
    assert_eq!(w.c.sellers.get(&sid).unwrap().free(), 160_000);
    w.check();
}

