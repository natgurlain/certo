#[test]
fn exposure_freed_by_lazy_sweep_after_window() {
    let mut w = world_with_bond(1_000_000);
    let sid = w.sellers[0].0.clone();
    pay(&mut w, 400_000, 1);
    pay(&mut w, 400_000, 2);
    w.now_ms += 60_001; // seller0 window is 60 s
    w.ctx(&sid, 0);
    assert_eq!(w.c.get_seller(sid.clone()).unwrap()["free_capacity"], "1000000"); // view simulates the sweep
    assert_eq!(w.c.sellers.get(&sid).unwrap().reserved, 840_000); // storage untouched by the view
    let id3 = pay(&mut w, 400_000, 3); // pay sweeps first
    let s = w.c.sellers.get(&sid).unwrap().clone();
    assert_eq!((s.reserved, s.lifetime_calls, s.lifetime_volume), (420_000, 2, 800_000));
    assert!(w.c.calls.get(&id3).is_some());
    w.check();
}

