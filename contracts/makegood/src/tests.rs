struct World {
    c: Contract,
    now_ms: u64,
    /// Model of the contract's token balance, from ft_on_transfer inflows and ft_transfer receipts.
    balance: u128,
    sellers: Vec<(AccountId, SigningKey)>,
    buyers: Vec<AccountId>,
    calls: Vec<Meta>,
    jurors: Vec<SigningKey>,
    rng: StdRng,
    quote_n: u64,
    stats: std::collections::BTreeMap<&'static str, u32>,
}

struct Meta {
    id: String,
    canon: String,
    body: String,
    offer: u16,
    salt: [u8; 32],
}

fn mg() -> AccountId {
    acc("mg.near")
}
fn token() -> AccountId {
    acc("usdc.near")
}

impl World {
    fn ctx(&self, pred: &AccountId, deposit: u128) {
        testing_env!(VMContextBuilder::new()
            .current_account_id(mg())
            .predecessor_account_id(pred.clone())
            .signer_account_id(pred.clone())
            .block_timestamp(self.now_ms * 1_000_000)
            .attached_deposit(NearToken::from_yoctonear(deposit))
            .prepaid_gas(Gas::from_tgas(300))
            .build());
    }

    fn new(seed: u64) -> Self {
        let mut rng = StdRng::seed_from_u64(seed);
        let jurors: Vec<SigningKey> = (0..3).map(|_| SigningKey::from_bytes(&rng.gen())).collect();
        // fresh storage for every world
        near_sdk::env::set_blockchain_interface(near_sdk::MockedBlockchain::new(
            VMContextBuilder::new().current_account_id(mg()).build(),
            near_sdk::test_vm_config(),
            near_sdk::RuntimeFeesConfig::test(),
            vec![],
            Default::default(),
            Default::default(),
            None,
        ));
        let c = Contract::new(
            acc("owner.near"),
            token(),
            acc("resolver.near"),
            test_cfg(),
            jurors
                .iter()
                .enumerate()
                .map(|(i, k)| JurorArg {
                    model_id: MODELS[i].into(),
                    pubkey: encode::to_hex(k.verifying_key().as_bytes()),
                    attestation_sha256: "00".repeat(32),
                })
                .collect(),
            None,
        );
        let mut w = World {
            c,
            now_ms: 1_800_000_000_000,
            balance: 0,
            sellers: vec![],
            buyers: (0..3).map(|i| acc(&format!("buyer{i}.near"))).collect(),
            calls: vec![],
            jurors,
            rng,
            quote_n: 0,
            stats: Default::default(),
        };
        for i in 0..2 {
            let id = acc(&format!("seller{i}.near"));
            let key = SigningKey::from_bytes(&w.rng.gen());
            w.ctx(&id, NEAR);
            w.c.register_seller(encode::to_hex(key.verifying_key().as_bytes()), 60_000 + 30_000 * i as u64);
            w.ctx(&id, 0);
            w.c.add_terms("t1".into(), "Return data about the requested token.".into(), None, None, None, true);
            w.sellers.push((id, key));
        }
        w
    }

    /// An `ft_on_transfer` from the token that is expected to succeed (returns 0 used).
    fn transfer_in(&mut self, sender: &AccountId, amount: u128, msg: serde_json::Value) {
        self.ctx(&token(), 0);
        let _ = self.c.ft_on_transfer(sender.clone(), U128(amount), msg.to_string());
        self.balance += amount;
        self.settle_receipts();
    }

    /// Apply outgoing ft_transfer receipts to the balance model; fail ~10% of them.
    fn settle_receipts(&mut self) {
        let mut outs = vec![];
        for r in get_created_receipts() {
            for a in r.actions {
                if let MockAction::FunctionCallWeight { method_name, args, .. } = a {
                    if method_name == b"ft_transfer" {
                        let v: serde_json::Value = serde_json::from_slice(&args).unwrap();
                        let amt: u128 = v["amount"].as_str().unwrap().parse().unwrap();
                        outs.push((acc(v["receiver_id"].as_str().unwrap()), amt));
                    }
                }
            }
        }
        for (to, amt) in outs {
            assert!(amt > 0, "zero transfer created");
            if self.rng.gen_bool(0.1) {
                // transfer failed: tokens stay; the callback credits claimable
                testing_env!(
                    VMContextBuilder::new()
                        .current_account_id(mg())
                        .predecessor_account_id(mg())
                        .block_timestamp(self.now_ms * 1_000_000)
                        .build(),
                    near_sdk::test_vm_config(),
                    near_sdk::RuntimeFeesConfig::test(),
                    Default::default(),
                    vec![PromiseResult::Failed],
                );
                assert!(!self.c.on_transfer_done(to, U128(amt)));
                self.bump("transfer_failed");
            } else {
                self.balance -= amt;
            }
        }
    }

    fn bump(&mut self, k: &'static str) {
        *self.stats.entry(k).or_default() += 1;
    }

    fn check(&self) {
        let mut held: u128 = self.c.treasury;
        let everyone: Vec<AccountId> = self
            .sellers
            .iter()
            .map(|s| s.0.clone())
            .chain(self.buyers.iter().cloned())
            .chain([acc("owner.near")])
            .collect();
        for a in &everyone {
            held += self.c.claimable.get(a).copied().unwrap_or(0);
        }
        for (sid, _) in &self.sellers {
            let s = self.c.sellers.get(sid).unwrap();
            assert!(s.bond >= s.reserved + s.disputed_reserved, "I1 violated for {sid}: {s:?}");
            held += s.bond;
            let (mut open, mut disp) = (0, 0);
            for m in &self.calls {
                if let Some(c) = self.c.calls.get(&m.id) {
                    if &c.seller == sid {
                        if c.status == CallStatus::Open {
                            open += c.reserve
                        } else {
                            disp += c.reserve
                        }
                    }
                }
            }
            assert_eq!((open, disp), (s.reserved, s.disputed_reserved), "reserve sums for {sid}");
        }
        for m in &self.calls {
            if let Some(c) = self.c.calls.get(&m.id) {
                held += c.dispute.as_ref().map(|d| d.stake).unwrap_or(0);
            }
        }
        assert_eq!(held, self.balance, "token balance = bonds + stakes + treasury + claimable");
    }

    fn live(&self, pred: impl Fn(&Call, u64) -> bool) -> Vec<usize> {
        (0..self.calls.len())
            .filter(|&i| self.c.calls.get(&self.calls[i].id).map(|c| pred(c, self.now_ms)).unwrap_or(false))
            .collect()
    }

    fn pick(&mut self, v: Vec<usize>) -> Option<usize> {
        (!v.is_empty()).then(|| v[self.rng.gen_range(0..v.len())])
    }

    fn receipt_sig(&self, m: &Meta, code: u16) -> (String, Base64VecU8, u64) {
        let c = self.c.calls.get(&m.id).unwrap();
        let si = self.sellers.iter().position(|s| s.0 == c.seller).unwrap();
        let rh = sha(m.body.as_bytes());
        let served = c.paid_at_ms + 10;
        let t = receipt_text(mg().as_str(), &m.id, c.buyer.as_str(), c.price, &c.terms_id, &c.request_hash, &rh, code, served);
        let sig = self.sellers[si].1.sign(t.as_bytes()).to_bytes().to_vec();
        (encode::to_hex(&rh), Base64VecU8(sig), served)
    }

    fn step(&mut self) {
        match self.rng.gen_range(0..15) {
            0..=2 => {
                let si = self.rng.gen_range(0..self.sellers.len());
                let bi = self.rng.gen_range(0..self.buyers.len());
                let price = self.rng.gen_range(10_000..=1_000_000u128);
                let sid = self.sellers[si].0.clone();
                self.ctx(&sid, 0);
                if !self.c.quote(sid.clone(), U128(price))["would_fit"].as_bool().unwrap() {
                    self.bump("pay_skipped_no_fit");
                    return;
                }
                self.quote_n += 1;
                let quote = format!("{:032x}", self.quote_n);
                let canon = format!("GET\n/v1/q?n={}\n", self.quote_n);
                let buyer = self.buyers[bi].clone();
                self.transfer_in(
                    &buyer,
                    price,
                    json!({"action":"pay","seller":sid,"quote_id":quote,"terms_id":"t1",
                           "request_hash": encode::to_hex(&sha(canon.as_bytes()))}),
                );
                let salt: [u8; 32] = self.rng.gen();
                let offer = self.rng.gen_range(0..=100u16) * 100;
                self.calls.push(Meta {
                    id: format!("{sid}/{quote}"),
                    canon,
                    body: format!("{{\"token\":\"NEO\",\"n\":{}}}", self.quote_n),
                    offer,
                    salt,
                });
                self.bump("pay");
            }
            3 => {
                let si = self.rng.gen_range(0..self.sellers.len());
                let amt = self.rng.gen_range(500_000..=3_000_000u128);
                let sid = self.sellers[si].0.clone();
                self.transfer_in(&sid, amt, json!({"action":"bond"}));
                self.bump("bond");
            }
            4 => {
                let si = self.rng.gen_range(0..self.sellers.len());
                let sid = self.sellers[si].0.clone();
                self.ctx(&sid, 0);
                let free: u128 =
                    self.c.get_seller(sid.clone()).unwrap()["free_capacity"].as_str().unwrap().parse().unwrap();
                if free == 0 {
                    return;
                }
                let amt = self.rng.gen_range(1..=free);
                drop(self.c.withdraw_bond(U128(amt)));
                self.settle_receipts();
                self.bump("withdraw_bond");
            }
            5 => {
                self.now_ms += self.rng.gen_range(0..=40_000);
            }
            6 => {
                let si = self.rng.gen_range(0..self.sellers.len());
                let sid = self.sellers[si].0.clone();
                self.ctx(&acc("anyone.near"), 0);
                self.c.release(sid, None);
                self.bump("release");
            }
            7 => {
                let Some(i) = self.pick(self.live(|c, now| c.status == CallStatus::Open && now <= c.expires_at_ms)) else {
                    return;
                };
                let (rh, sig, served) = self.receipt_sig(&self.calls[i], 503);
                let buyer = self.c.calls.get(&self.calls[i].id).unwrap().buyer.clone();
                self.ctx(&buyer, 0);
                self.c.claim_error(self.calls[i].id.clone(), rh, 503, served, sig);
                self.settle_receipts();
                self.bump("claim_error");
            }
            8 | 9 => {
                let Some(i) = self.pick(self.live(|c, now| c.status == CallStatus::Open && now <= c.expires_at_ms)) else {
                    return;
                };
                let c = self.c.calls.get(&self.calls[i].id).unwrap().clone();
                let need = fees::required_stake(self.c.base_stake(c.price), &self.c.buyer_rec(&c.buyer));
                let stake = need + self.rng.gen_range(0..=1000);
                let content = self.rng.gen_bool(0.5);
                let m = &self.calls[i];
                let msg = if !content {
                    json!({"action":"dispute","kind":"non_delivery","call_id":m.id})
                } else {
                    let (rh, sig, served) = self.receipt_sig(m, 200);
                    json!({"action":"dispute","kind":"content","call_id":m.id,"response_hash":rh,"status_code":200,
                           "served_at_ms":served,"sig":sig,
                           "offer_commit": encode::to_hex(&sha(&commit_preimage(m.offer, &m.salt)))})
                };
                self.transfer_in(&c.buyer, stake, msg);
                self.bump(if content { "dispute_content" } else { "dispute_non_delivery" });
            }
            10 => {
                let ans = self.c.cfg.answer_ms;
                let Some(i) = self.pick(self.live(|c, now| {
                    c.status == CallStatus::Disputed && now <= c.dispute.as_ref().unwrap().opened_at_ms + ans
                })) else {
                    return;
                };
                let seller = self.c.calls.get(&self.calls[i].id).unwrap().seller.clone();
                let offer = self.rng.gen_range(0..=100u16) * 100;
                self.ctx(&seller, 0);
                self.c.answer(self.calls[i].id.clone(), offer);
                self.bump("answer");
            }
            11 => {
                let ans = self.c.cfg.answer_ms;
                let Some(i) = self.pick(self.live(|c, now| {
                    c.status == CallStatus::NonDeliveryClaimed && now <= c.dispute.as_ref().unwrap().opened_at_ms + ans
                })) else {
                    return;
                };
                let code = if self.rng.gen_bool(0.8) { 200 } else { 502 };
                let (rh, sig, served) = self.receipt_sig(&self.calls[i], code);
                let seller = self.c.calls.get(&self.calls[i].id).unwrap().seller.clone();
                self.ctx(&seller, 0);
                let m = &self.calls[i];
                self.c.cure(m.id.clone(), rh, code, served, sig, m.body.clone());
                self.settle_receipts();
                self.bump("cure");
            }
            12 => {
                let (ans, dl) = (self.c.cfg.answer_ms, self.c.cfg.panel_deadline_ms);
                let Some(i) = self.pick(self.live(|c, now| {
                    let d = c.dispute.as_ref();
                    match c.status {
                        CallStatus::NonDeliveryClaimed | CallStatus::Disputed => now > d.unwrap().opened_at_ms + ans,
                        CallStatus::Answered => now > d.unwrap().answered_at_ms + dl,
                        CallStatus::Open => false,
                    }
                })) else {
                    return;
                };
                self.ctx(&acc("anyone.near"), 0);
                let reveal = self.rng.gen_bool(0.5);
                let m = &self.calls[i];
                let (o, s) = if reveal { (Some(m.offer), Some(encode::to_hex(&m.salt))) } else { (None, None) };
                self.c.resolve_default(m.id.clone(), o, s);
                self.settle_receipts();
                self.bump("resolve_default");
            }
            13 => {
                let Some(i) = self.pick(self.live(|c, _| c.status == CallStatus::Answered)) else { return };
                let c = self.c.calls.get(&self.calls[i].id).unwrap().clone();
                let seller_bps = c.dispute.as_ref().unwrap().seller_offer_bps.unwrap();
                let terms = self.c.terms.get(&(c.seller.clone(), c.terms_id.clone())).unwrap().text.clone();
                let buyer_wins = self.rng.gen_bool(0.5);
                let third = self.rng.gen_range(0..3);
                let m = &self.calls[i];
                let ballots: Vec<Ballot> = (0..3)
                    .map(|j| {
                        let side = if j < 2 { Some(buyer_wins) } else { [Some(true), Some(false), None][third] };
                        let content = match side {
                            Some(b) if b == encode::buyer_is_x(j) => "X",
                            Some(_) => "Y",
                            None => "maybe",
                        };
                        let resp = json!({"choices":[{"message":{"role":"assistant","content":content}}]}).to_string();
                        let body = panel_request_body(j, MODELS[j], &terms, &m.canon, &m.body, m.offer, seller_bps);
                        let text = format!(
                            "{}:{}:{}",
                            MODELS[j],
                            encode::to_hex(&sha(body.as_bytes())),
                            encode::to_hex(&sha(resp.as_bytes()))
                        );
                        Ballot {
                            response_body: resp,
                            signature: Base64VecU8(self.jurors[j].sign(text.as_bytes()).to_bytes().to_vec()),
                            kind: "provider_tee".into(),
                            request_hash: None,
                        }
                    })
                    .collect();
                let settled = seller_bps >= m.offer;
                let (id, offer, salt, canon, body) =
                    (m.id.clone(), m.offer, encode::to_hex(&m.salt), m.canon.clone(), m.body.clone());
                self.ctx(&acc("resolver.near"), 0);
                self.c.resolve(id, offer, salt, canon, body, ballots);
                self.settle_receipts();
                self.bump(if settled { "resolve_settled" } else { "resolve_panel" });
            }
            _ => {
                let who: Vec<AccountId> = self
                    .sellers
                    .iter()
                    .map(|s| s.0.clone())
                    .chain(self.buyers.iter().cloned())
                    .filter(|a| self.c.claimable.get(a).copied().unwrap_or(0) > 0)
                    .collect();
                if let Some(a) = who.first() {
                    self.ctx(a, 0);
                    drop(self.c.withdraw_claimable());
                    self.settle_receipts();
                    self.bump("withdraw_claimable");
                } else if self.c.treasury > 0 {
                    self.ctx(&acc("owner.near"), 0);
                    let amt = self.rng.gen_range(1..=self.c.treasury);
                    drop(self.c.withdraw_treasury(U128(amt), acc("owner.near")));
                    self.settle_receipts();
                    self.bump("withdraw_treasury");
                }
            }
        }
    }
}

/// G13: 500 random sequences of pay/bond/withdraw/release/claim/dispute/answer/cure/
/// resolve/resolve_default/claimable with ~10% failed payouts; after every step
/// I1 holds and the contract's token balance equals Σ bonds + Σ stakes + treasury + Σ claimable.
#[test]
fn g13_solvency_property() {
    let mut total: std::collections::BTreeMap<&'static str, u32> = Default::default();
    for seed in 0..500u64 {
        let mut w = World::new(seed);
        for i in 0..w.sellers.len() {
            let sid = w.sellers[i].0.clone();
            w.transfer_in(&sid, 2_000_000, json!({"action":"bond"}));
        }
        w.check();
        for _ in 0..60 {
            w.step();
            w.check();
        }
        for (k, v) in w.stats {
            *total.entry(k).or_default() += v;
        }
    }
    println!("G13 operation counts over 500 sequences: {total:?}");
    for k in [
        "pay",
        "bond",
        "withdraw_bond",
        "claim_error",
        "dispute_content",
        "dispute_non_delivery",
        "answer",
        "cure",
        "resolve_default",
        "resolve_panel",
        "resolve_settled",
        "withdraw_claimable",
        "transfer_failed",
    ] {
        assert!(total.get(k).copied().unwrap_or(0) > 20, "operation {k} too rare: {total:?}");
    }
}

